@Immutable
internal data class EditorialHomeCopy(
    val seeAll: String,
    val seeAllCdTemplate: String,
    val play: String,
    val playCdTemplate: String,
    val loadingPlay: String,
    val retry: String,
    val sectionError: String,
    val featuredTitle: String,
    val featuredSubtitle: String,
    val featuredEmpty: String,
    val featuredCdTemplate: String,
    val resumeTitle: String,
    val resumeSubtitle: String,
    val resumeEmpty: String,
    val newReleasesTitle: String,
    val newReleasesSubtitle: String,
    val newReleasesEmpty: String,
    val essentialsTitle: String,
    val essentialsSubtitle: String,
    val essentialsEmpty: String,
    val trendingTitle: String,
    val trendingSubtitle: String,
    val trendingEmpty: String,
    val trendingRankCdTemplate: String,
    val moodsTitle: String,
    val moodsSubtitle: String,
    val moodsEmpty: String,
    val moodsChipCdTemplate: String,
    val exploreTitle: String,
    val exploreEmpty: String,
    val tabCollections: String,
    val tabSongs: String,
    val filterAlphabet: String,
    val filterAlbum: String,
    val filterArtist: String,
    val filterRecent: String,
    val letterAll: String,
    val shuffle: String,
    val collectionsSavedTitle: String,
    val collectionsGroupedTitle: String,
    val unknownAlbum: String,
    val unknownArtist: String,
    val cancelDownloadCdTemplate: String,
    val toggleFavoriteCdTemplate: String,
    val favoritesTitle: String,
    val favoritesSubtitle: String,
    val downloadsSubtitle: String,
) {
    fun seeAllCd(sectionTitle: String): String = seeAllCdTemplate.replace("%s", sectionTitle)
    fun playCd(title: String): String = playCdTemplate.replace("%s", title)
    fun featuredCd(title: String): String = featuredCdTemplate.replace("%s", title)
    fun trendingRankCd(rank: Int, title: String, artist: String): String =
        trendingRankCdTemplate
            .replace("%1\$d", rank.toString())
            .replace("%2\$s", title)
            .replace("%3\$s", artist)
    fun moodsChipCd(title: String): String = moodsChipCdTemplate.replace("%s", title)
    fun cancelDownloadCd(title: String): String = cancelDownloadCdTemplate.replace("%s", title)
    fun toggleFavoriteCd(title: String): String = toggleFavoriteCdTemplate.replace("%s", title)
}

